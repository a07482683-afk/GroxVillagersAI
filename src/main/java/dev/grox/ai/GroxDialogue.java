package dev.grox.ai;

import net.minecraft.entity.passive.VillagerEntity;

import java.util.Locale;
import java.util.concurrent.ThreadLocalRandom;

public final class GroxDialogue {
    private GroxDialogue() {}

    private static String pick(String... lines) {
        return lines[ThreadLocalRandom.current().nextInt(lines.length)];
    }

    public static String greeting(GroxMemory m, VillagerEntity villager) {
        if (m.fear > 65) return pick(
                "Пожалуйста, не шуми... Я всё ещё тревожусь.",
                "Я немного напуган. Давай поговорим спокойно.",
                "Рад тебя видеть, но сейчас мне не по себе.");
        if (m.trust > 75) return pick(
                "О, ты вернулся! Я уже привык к нашим разговорам.",
                "Привет, друг! Какие новости принёс?",
                "Хорошо, что ты заглянул. Расскажешь, что видел?");
        if (m.mood < 25) return pick(
                "Привет... Сегодня я немного грущу.",
                "Рад встрече. Хотя день выдался непростой.",
                "Можно просто немного поговорить? Мне станет легче.");
        return pick(
                "Привет! Как прошла твоя дорога?",
                "Здравствуй! Что интересного случилось сегодня?",
                "Рад встрече. В деревне пока спокойно.",
                "Привет! Ты исследуешь окрестности?",
                "Снова ты! Есть какие-нибудь новости?",
                "Здравствуй. О чём хочешь поговорить?");
    }

    public static String answer(String input, GroxMemory m, VillagerEntity villager) {
        String s = input.toLowerCase(Locale.ROOT);
        if (s.contains("привет") || s.contains("здравств")) return greeting(m, villager);
        if (s.contains("как дела") || s.contains("как ты")) {
            if (m.mood > 70) return pick("У меня сегодня отличное настроение!", "Всё хорошо! День спокойный.", "Я чувствую себя бодро. А у тебя?");
            if (m.mood < 30) return pick("Не очень... Надеюсь, завтра будет лучше.", "Я немного устал. Спасибо, что спросил.", "Бывает лучше. Может, поговорим о чём-нибудь хорошем?");
            return pick("Всё нормально, спасибо.", "День идёт своим чередом.", "Неплохо! А как твои дела?");
        }
        if (s.contains("страш") || s.contains("боишься")) {
            return m.fear > 35 ? pick("Да, мне сейчас тревожно.", "Я слышал опасные звуки неподалёку.", "Мне спокойнее, когда рядом друзья.")
                    : pick("Сейчас я спокоен.", "Я стараюсь не бояться понапрасну.", "Пока всё тихо.");
        }
        if (s.contains("друг") || s.contains("довер")) {
            return m.trust > 60 ? pick("Я уже начинаю тебе доверять.", "Ты стал для меня хорошим знакомым.", "Думаю, мы можем стать друзьями.")
                    : pick("Доверие нужно заслужить.", "Давай узнаем друг друга получше.", "Пока я ещё присматриваюсь к тебе.");
        }
        if (s.contains("помощ") || s.contains("работ")) return pick(
                "Я могу помочь, если это не слишком опасно.",
                "Расскажи подробнее, что нужно сделать.",
                "Давай подумаем, как это организовать.");
        if (s.contains("пока") || s.contains("до свид")) return pick(
                "До встречи! Я запомню наш разговор.",
                "Удачной дороги. Заглядывай ещё!",
                "Пока! Береги себя в пути.");
        if (s.contains("торг") || s.contains("обмен")) return "Нажми по мне ПКМ без Shift — откроется обычная торговля, если у меня есть профессия и предложения.";
        if (s.contains("дом") || s.contains("деревн")) return pick(
                "Это наш дом. Я хочу, чтобы здесь было безопасно.",
                "Мне нравится наша деревня. Здесь живут мои знакомые.",
                "Я надеюсь, что деревня будет процветать.");
        if (s.contains("имя") || s.contains("зовут")) return "Меня зовут " + villager.getName().getString() + ". А как зовут тебя?";
        if (s.contains("погода") || s.contains("дожд")) return pick(
                "Погода меняется, но это часть жизни.",
                "Надеюсь, скоро выглянет солнце.",
                "После дождя деревня выглядит особенно свежей.");
        if (s.contains("рад") || s.contains("счаст")) return m.mood > 55
                ? "Да, сегодня я рад! Спасибо, что заметил."
                : "Пока настроение не очень, но добрые слова помогают.";
        if (s.contains("зомби") || s.contains("монстр") || s.contains("опас")) return m.fear > 40
                ? "Я волнуюсь из-за опасностей. Лучше держаться вместе."
                : "Если появится угроза, нужно предупредить остальных.";
        return pick(
                "Интересная мысль. Расскажи об этом немного подробнее.",
                "Я понял тебя. А что ты думаешь об этом сам?",
                "Раньше я об этом не задумывался. Запомню твои слова.",
                "Хм... Мне нужно немного подумать.",
                "Можешь объяснить по-другому? Я хочу понять.");
    }
}
