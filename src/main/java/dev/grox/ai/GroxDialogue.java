    private static String richReply(GroxMemory m) {
        String opener = pick(OPENERS);
        String mood = pick(MOOD_LINES);
        String observation = pick(OBSERVATIONS);
        String bridge = pick(BRIDGES);
        String question = pick(QUESTIONS);

        if (m.fear > 65) mood = pick("Я пока немного напуган.", "Мне спокойнее в безопасном месте.", "Давай говорить тихо и не спешить.");
        else if (m.trust > 75) mood = pick("Я рад поговорить с тобой, как со старым другом.", "С тобой я могу говорить откровеннее.", "Я уже хорошо тебя знаю.");
        else if (m.mood < 25) mood = pick("Сегодня мне немного грустно.", "У меня выдался трудный день.", "Надеюсь, скоро настроение улучшится.");

        if (m.curiosity > 75) question = pick("А что находится дальше за горизонтом?", "Можешь рассказать ещё одну необычную историю?", "Как ты это обнаружил?", "Что нового ты хотел бы исследовать?");
        if (m.social < 20) observation = pick("Иногда мне не хватает общения.", "Было бы здорово чаще встречаться с соседями.", "Мне хочется познакомиться с кем-нибудь новым.");

        return opener + " " + mood + " " + observation + " " + bridge + " " + question;
    }

    public static String greeting(GroxMemory m, VillagerEntity villager) {
        if (m.fear > 65) return pick("Пожалуйста, не шуми... Я всё ещё тревожусь.", "Я немного напуган. Давай поговорим спокойно.", "Рад тебя видеть, но сейчас мне не по себе.");
        if (m.trust > 75) return pick("О, ты вернулся! Я уже привык к нашим разговорам.", "Привет, друг! Какие новости принёс?", "Хорошо, что ты заглянул. Расскажешь, что видел?");
        if (m.mood < 25) return pick("Привет... Сегодня я немного грущу.", "Рад встрече. Хотя день выдался непростой.", "Можно просто немного поговорить? Мне станет легче.");
        return richReply(m);
    }

    public static String answer(String input, GroxMemory m, VillagerEntity villager) {
        String s = input.toLowerCase(Locale.ROOT);
        if (s.contains("привет") || s.contains("здравств")) return greeting(m, villager);
        if (s.contains("как дела") || s.contains("как ты")) {
            if (m.mood > 70) return pick("У меня сегодня отличное настроение!", "Всё хорошо! День спокойный.", "Я чувствую себя бодро. А у тебя?");
            if (m.mood < 30) return pick("Не очень... Надеюсь, завтра будет лучше.", "Я немного устал. Спасибо, что спросил.", "Бывает лучше. Может, поговорим о чём-нибудь хорошем?");
            return pick("Всё нормально, спасибо.", "День идёт своим чередом.", "Неплохо! А как твои дела?");
        }
        if (s.contains("страш") || s.contains("боишься")) return m.fear > 35
                ? pick("Да, мне сейчас тревожно.", "Я слышал опасные звуки неподалёку.", "Мне спокойнее, когда рядом друзья.")
                : pick("Сейчас я спокоен.", "Я стараюсь не бояться понапрасну.", "Пока всё тихо.");
        if (s.contains("друг") || s.contains("довер")) return m.trust > 60
                ? pick("Я уже начинаю тебе доверять.", "Ты стал для меня хорошим знакомым.", "Думаю, мы можем стать друзьями.")
                : pick("Доверие нужно заслужить.", "Давай узнаем друг друга получше.", "Пока я ещё присматриваюсь к тебе.");
        if (s.contains("помощ") || s.contains("работ")) return pick("Я могу помочь, если это не слишком опасно.", "Расскажи подробнее, что нужно сделать.", "Давай подумаем, как это организовать.");
        if (s.contains("пока") || s.contains("до свид")) return pick("До встречи! Я запомню наш разговор.", "Удачной дороги. Заглядывай ещё!", "Пока! Береги себя в пути.");
        if (s.contains("торг") || s.contains("обмен")) return "Нажми по мне ПКМ без Shift — откроется обычная торговля, если у меня есть профессия и предложения.";
        if (s.contains("дом") || s.contains("деревн")) return pick("Это наш дом. Я хочу, чтобы здесь было безопасно.", "Мне нравится наша деревня. Здесь живут мои знакомые.", "Я надеюсь, что деревня будет процветать.");
        if (s.contains("имя") || s.contains("зовут")) return "Меня зовут " + villager.getName().getString() + ". А как зовут тебя?";
        if (s.contains("погода") || s.contains("дожд")) return pick("Погода меняется, но это часть жизни.", "Надеюсь, скоро выглянет солнце.", "После дождя деревня выглядит особенно свежей.");
        if (s.contains("рад") || s.contains("счаст")) return m.mood > 55 ? "Да, сегодня я рад! Спасибо, что заметил." : "Пока настроение не очень, но добрые слова помогают.";
        if (s.contains("зомби") || s.contains("монстр") || s.contains("опас")) return m.fear > 40 ? "Я волнуюсь из-за опасностей. Лучше держаться вместе." : "Если появится угроза, нужно предупредить остальных.";
        return richReply(m);
    }
